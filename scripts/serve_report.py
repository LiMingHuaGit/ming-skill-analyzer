#!/usr/bin/env python3
"""Read-only loopback HTTP server for ming-skill-analyzer live report previews.

Serves the report HTML and provides a JSON file API so the browser can read
target Skill files on demand.  Never binds outside 127.0.0.1.
"""

from __future__ import annotations

import argparse
import hashlib
import http.server
import ipaddress
import json
import mimetypes
import os
import socketserver
import sys
import threading
import urllib.parse
import webbrowser
from pathlib import Path

MAX_FILE_BYTES = 2_000_000
SENSITIVE_NAMES = {
    ".env", "credentials.json", "secrets.json", "id_rsa", "id_ed25519",
    "service-account.json", "service_account.json", "auth.json",
}
SKIP_DIRS = {".git", ".hg", ".svn", ".venv", "venv", "node_modules", "__pycache__"}
TEXT_EXTENSIONS = {
    ".md", ".markdown", ".txt", ".py", ".js", ".mjs", ".cjs", ".ts", ".tsx",
    ".jsx", ".json", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".conf",
    ".sh", ".bash", ".zsh", ".fish", ".swift", ".java", ".kt", ".go",
    ".rs", ".rb", ".php", ".html", ".css", ".scss", ".sql", ".xml", ".csv", ".svg",
}
IMAGE_EXTENSIONS = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".ico"}
PREVIEW_EXTENSIONS = IMAGE_EXTENSIONS | {".pdf", ".mp4", ".mov", ".mp3", ".wav"}


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--report", required=True, type=Path,
                   help="Path to the report.html generated by render_report.py")
    p.add_argument("--skill-root", required=True, type=Path,
                   help="Root directory of the target Skill (must contain SKILL.md)")
    p.add_argument("--host", default="127.0.0.1",
                   help="Bind address — must be a loopback address (default: 127.0.0.1)")
    p.add_argument("--port", type=int, default=8765,
                   help="TCP port (default: 8765; retried automatically if occupied)")
    p.add_argument("--open", action="store_true",
                   help="Open the report URL in the default browser after starting")
    return p.parse_args()


def is_loopback(host: str) -> bool:
    try:
        return ipaddress.ip_address(host).is_loopback
    except ValueError:
        return host in ("localhost",)


def is_sensitive(path: Path) -> bool:
    name = path.name.lower()
    return name in SENSITIVE_NAMES or name.endswith((".pem", ".key", ".p12", ".pfx"))


def safe_relative(root: Path, path: Path) -> Path | None:
    """Return path relative to root, or None if it escapes root or is a symlink."""
    try:
        # Resolve symlinks in the requested path only up to root level
        resolved = (root / path).resolve()
        resolved.relative_to(root.resolve())
        # Reject symlinks inside the skill tree
        if resolved.is_symlink():
            return None
        return resolved.relative_to(root.resolve())
    except (ValueError, OSError):
        return None


def read_file_record(root: Path, rel: Path) -> dict:
    """Return a file metadata + content record for the API."""
    full = root / rel
    relative = rel.as_posix()
    size = full.stat().st_size
    mtime_ns = full.stat().st_mtime_ns
    record: dict = {
        "path": relative,
        "size": size,
        "mtime_ns": mtime_ns,
        "sha256": "",
        "text": None,
        "line_count": None,
        "truncated": False,
        "sensitive": False,
        "redactions": 0,
        "skip_reason": None,
        "preview_mime": None,
        "preview_base64": None,
        "raw_url": None,
    }
    if is_sensitive(full):
        record["sensitive"] = True
        record["skip_reason"] = "credential-like file"
        return record
    if size > MAX_FILE_BYTES:
        record["skip_reason"] = f"file exceeds {MAX_FILE_BYTES} bytes"
        return record

    data = full.read_bytes()
    record["sha256"] = hashlib.sha256(data).hexdigest()
    ext = full.suffix.lower()

    # Text files
    if ext in TEXT_EXTENSIONS or full.name.lower() == "skill.md":
        for encoding in ("utf-8", "utf-8-sig", "utf-16"):
            try:
                text = data.decode(encoding)
                record["text"] = text
                record["line_count"] = len(text.splitlines())
                return record
            except UnicodeDecodeError:
                continue
        record["skip_reason"] = "binary or unsupported text format"
        return record

    # Preview-able media (images etc.) – serve via raw URL
    if ext in PREVIEW_EXTENSIONS:
        mime = mimetypes.guess_type(str(full))[0] or "application/octet-stream"
        record["preview_mime"] = mime
        record["raw_url"] = f"/api/raw?path={urllib.parse.quote(relative)}"
        return record

    record["skip_reason"] = "binary or unsupported text format"
    return record


def list_skill_files(root: Path) -> list[dict]:
    records = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(root)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        if path.is_symlink():
            continue
        records.append({
            "path": rel.as_posix(),
            "size": path.stat().st_size,
            "mtime_ns": path.stat().st_mtime_ns,
            "sha256": "",
            "text": None,
            "line_count": None,
            "truncated": False,
            "sensitive": is_sensitive(path),
            "redactions": 0,
            "skip_reason": "credential-like file" if is_sensitive(path) else None,
            "preview_mime": None,
            "preview_base64": None,
            "raw_url": None,
        })
    return records


class Handler(http.server.BaseHTTPRequestHandler):
    report_path: Path
    skill_root: Path

    def log_message(self, fmt: str, *args: object) -> None:  # silence default logging
        pass

    def send_json(self, data: object, status: int = 200) -> None:
        body = json.dumps(data, ensure_ascii=False).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def send_error_json(self, status: int, message: str) -> None:
        self.send_json({"error": message}, status)

    def do_GET(self) -> None:  # noqa: N802
        parsed = urllib.parse.urlparse(self.path)
        params = dict(urllib.parse.parse_qsl(parsed.query))

        # Report HTML
        if parsed.path in ("/", "/report.html"):
            try:
                body = self.report_path.read_bytes()
            except OSError as exc:
                self.send_error_json(500, str(exc))
                return
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)
            return

        # Status endpoint
        if parsed.path == "/api/status":
            self.send_json({
                "status": "serving",
                "report": str(self.report_path),
                "skill_root": str(self.skill_root),
            })
            return

        # File list
        if parsed.path == "/api/files":
            try:
                records = list_skill_files(self.skill_root)
            except OSError as exc:
                self.send_error_json(500, str(exc))
                return
            self.send_json({"files": records})
            return

        # Individual file
        if parsed.path == "/api/file":
            rel_str = params.get("path", "")
            if not rel_str:
                self.send_error_json(400, "path parameter required")
                return
            rel = safe_relative(self.skill_root, Path(rel_str))
            if rel is None:
                self.send_error_json(403, "path is outside skill root or is a symlink")
                return
            full = self.skill_root / rel
            if not full.is_file():
                self.send_error_json(404, f"file not found: {rel_str}")
                return
            if is_sensitive(full):
                self.send_error_json(403, "sensitive file access denied")
                return
            try:
                record = read_file_record(self.skill_root, rel)
            except OSError as exc:
                self.send_error_json(500, str(exc))
                return
            self.send_json(record)
            return

        # Raw binary (images, PDF…)
        if parsed.path == "/api/raw":
            rel_str = params.get("path", "")
            if not rel_str:
                self.send_error_json(400, "path parameter required")
                return
            rel = safe_relative(self.skill_root, Path(rel_str))
            if rel is None:
                self.send_error_json(403, "path is outside skill root or is a symlink")
                return
            full = self.skill_root / rel
            if not full.is_file():
                self.send_error_json(404, f"file not found: {rel_str}")
                return
            if is_sensitive(full):
                self.send_error_json(403, "sensitive file access denied")
                return
            mime = mimetypes.guess_type(str(full))[0] or "application/octet-stream"
            try:
                data = full.read_bytes()
            except OSError as exc:
                self.send_error_json(500, str(exc))
                return
            self.send_response(200)
            self.send_header("Content-Type", mime)
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(data)
            return

        self.send_error_json(404, f"not found: {parsed.path}")


def make_handler(report_path: Path, skill_root: Path) -> type:
    class BoundHandler(Handler):
        pass
    BoundHandler.report_path = report_path
    BoundHandler.skill_root = skill_root
    return BoundHandler


def main() -> int:
    args = parse_args()

    if not is_loopback(args.host):
        raise SystemExit(f"error: host must be a loopback address, got {args.host!r}")
    if not args.report.is_file():
        raise SystemExit(f"error: report does not exist: {args.report}")
    skill_root = args.skill_root.expanduser().resolve()
    if not (skill_root / "SKILL.md").is_file():
        raise SystemExit(f"error: skill root must contain SKILL.md: {skill_root}")

    handler = make_handler(args.report.resolve(), skill_root)

    # Try the requested port, then auto-increment on EADDRINUSE
    port = args.port
    for attempt in range(20):
        try:
            server = socketserver.ThreadingTCPServer((args.host, port), handler)
            server.allow_reuse_address = True
            break
        except OSError as exc:
            if "Address already in use" in str(exc) and attempt < 19:
                port += 1
                continue
            raise SystemExit(f"error: could not bind to {args.host}:{port}: {exc}") from exc

    url = f"http://{args.host}:{server.server_address[1]}/"
    startup = json.dumps({
        "status": "serving",
        "url": url,
        "report": str(args.report.resolve()),
        "skill_root": str(skill_root),
        "host": args.host,
        "port": server.server_address[1],
    }, ensure_ascii=False)
    print(startup, flush=True)

    if args.open:
        threading.Timer(0.3, lambda: webbrowser.open(url)).start()

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
